//! The spi config, and the config files generated from it.

mod common;

use common::{load, load_env, scratch};
use spi::config::{Network, Which};
use spi::generate;

fn parse(text: &str) -> toml::Table {
    text.parse().unwrap()
}

#[test]
fn defaults_are_regtest_and_main_is_never_the_default() {
    let spi = load(&scratch("defaults"), None).unwrap();
    assert_eq!(spi.network, Network::Regtest);
    assert_eq!(spi.rpc_url, "http://127.0.0.1:18443");
    assert_eq!(spi.wallet, "psp-regtest");
    assert_eq!(spi.psp.bind, "127.0.0.1:3000");
    assert_eq!(spi.esp.bind, "127.0.0.1:3100");
    assert_eq!(spi.esp.admin_bind.as_deref(), Some("127.0.0.1:3101"));
    assert!(spi.create_wallet);
    let c = spi.cookie.display().to_string();
    assert_eq!(c, "/home/test/.bitcoin/regtest/.cookie");
    // An empty file is the same.
    let spi = load(&scratch("empty"), Some("")).unwrap();
    assert_eq!(spi.network, Network::Regtest);
}

#[test]
fn main_needs_to_be_written_down_and_changes_the_defaults() {
    let spi = load(&scratch("main"), Some("network = \"main\"")).unwrap();
    assert_eq!(spi.network, Network::Main);
    assert_eq!(spi.rpc_url, "http://127.0.0.1:8332");
    assert_eq!(spi.wallet, "psp-main");
    assert_eq!(
        spi.cookie.display().to_string(),
        "/home/test/.bitcoin/.cookie"
    );
    let spi = load_env(&scratch("main-env"), None, &[("SPI_NETWORK", "main")]).unwrap();
    assert_eq!(spi.network, Network::Main);
    let spi = load(&scratch("testnet"), Some("network = \"testnet\"")).unwrap();
    assert_eq!(
        spi.cookie.display().to_string(),
        "/home/test/.bitcoin/testnet3/.cookie"
    );
    assert_eq!(Network::Testnet.chain(), "test");
}

#[test]
fn the_environment_beats_the_file_and_the_file_beats_the_default() {
    let file =
        "network = \"signet\"\n[psp]\nbind = \"127.0.0.1:4000\"\n[esp]\nbind = \"127.0.0.1:4100\"";
    let spi = load_env(
        &scratch("env"),
        Some(file),
        &[("SPI_ESP_BIND", "127.0.0.1:5100")],
    )
    .unwrap();
    assert_eq!(spi.network, Network::Signet);
    assert_eq!(spi.psp.bind, "127.0.0.1:4000");
    assert_eq!(spi.esp.bind, "127.0.0.1:5100");
    let from = |k: &str| {
        spi.shown
            .iter()
            .find(|(key, _, _)| key == k)
            .map(|(_, _, f)| f.clone())
            .unwrap()
    };
    assert_eq!(from("esp.bind"), "env SPI_ESP_BIND");
    assert_eq!(from("psp.bind"), "spi.toml");
    assert_eq!(from("esp.admin_bind"), "default");
}

#[test]
fn every_problem_is_listed_and_unknown_keys_are_refused() {
    let file = "network = \"moon\"\nflavour = 1\n[bitcoind]\nrpc_url = \"ftp://x\"\nwallet = \"a/b\"\nextra = 1\n[psp]\nbind = \"nope\"";
    let problems = load(&scratch("bad"), Some(file)).unwrap_err();
    let all = problems.join("\n");
    for needle in [
        "network: `moon` is not a network",
        "flavour is not a setting",
        "must start with http",
        "must not contain `/`",
        "extra is not a setting",
        "psp.bind is `nope`",
    ] {
        assert!(all.contains(needle), "{needle} not in:\n{all}");
    }
    assert!(load(&scratch("toml"), Some("this is = = not toml")).is_err());
}

#[test]
fn the_generated_files_have_the_header_and_the_named_values() {
    let dir = scratch("gen");
    let spi = load(
        &dir,
        Some("network = \"regtest\"\n[bitcoind]\nwallet = \"mine\""),
    )
    .unwrap();
    let psp = generate::render(&spi, Which::Psp).unwrap();
    let esp = generate::render(&spi, Which::Esp).unwrap();
    for text in [&psp, &esp] {
        assert!(text.starts_with("# Generated by spi. Don't edit"), "{text}");
    }
    let p = parse(&psp);
    assert_eq!(p["bitcoin"]["network"].as_str(), Some("regtest"));
    assert_eq!(p["bitcoin"]["wallet"].as_str(), Some("mine"));
    assert_eq!(
        p["bitcoin"]["rpc_url"].as_str(),
        Some("http://127.0.0.1:18443")
    );
    assert_eq!(p["server"]["bind"].as_str(), Some("127.0.0.1:3000"));
    let e = parse(&esp);
    assert_eq!(e["server"]["bind"].as_str(), Some("127.0.0.1:3100"));
    assert_eq!(e["server"]["admin_bind"].as_str(), Some("127.0.0.1:3101"));
    assert_eq!(e["server"]["network"].as_str(), Some("regtest"));
    assert_eq!(e["psp"]["url"].as_str(), Some("http://127.0.0.1:3000"));
    // The same input gives the same text.
    assert_eq!(generate::render(&spi, Which::Psp).unwrap(), psp);
}

#[test]
fn the_psp_url_follows_the_psp_bind_and_a_wildcard_goes_through_loopback() {
    let spi = load(&scratch("url"), Some("[psp]\nbind = \"0.0.0.0:3999\"")).unwrap();
    let e = parse(&generate::render(&spi, Which::Esp).unwrap());
    assert_eq!(e["psp"]["url"].as_str(), Some("http://127.0.0.1:3999"));
}

#[test]
fn settings_spi_does_not_name_pass_through_unchanged() {
    let file = r#"
[psp.settings.settle]
min_confirmations = 3
price_tolerance = 0.005
[psp.settings.storage]
mint_state = ["aa", "bb"]
[psp.settings.bitcoin]
rpc_timeout_secs = 45
[esp.settings.terms]
maturity_days = 30
[esp.settings.exchange]
fee_per_byte = 7
"#;
    let spi = load(&scratch("pass"), Some(file)).unwrap();
    let p = parse(&generate::render(&spi, Which::Psp).unwrap());
    assert_eq!(p["settle"]["min_confirmations"].as_integer(), Some(3));
    assert_eq!(p["settle"]["price_tolerance"].as_float(), Some(0.005));
    let list: Vec<&str> = p["storage"]["mint_state"]
        .as_array()
        .unwrap()
        .iter()
        .map(|v| v.as_str().unwrap())
        .collect();
    assert_eq!(list, ["aa", "bb"]);
    // A pass-through key beside a key spi sets, in the same section.
    assert_eq!(p["bitcoin"]["rpc_timeout_secs"].as_integer(), Some(45));
    assert_eq!(p["bitcoin"]["network"].as_str(), Some("regtest"));
    let e = parse(&generate::render(&spi, Which::Esp).unwrap());
    assert_eq!(e["terms"]["maturity_days"].as_integer(), Some(30));
    assert_eq!(e["exchange"]["fee_per_byte"].as_integer(), Some(7));
    assert_eq!(e["server"]["network"].as_str(), Some("regtest"));
}

#[test]
fn a_setting_spi_names_cannot_also_be_passed_through() {
    for (file, needle) in [
        (
            "[psp.settings.bitcoin]\nnetwork = \"main\"",
            "psp.settings.bitcoin.network",
        ),
        (
            "[psp.settings.bitcoin]\nwallet = \"w\"",
            "psp.settings.bitcoin.wallet",
        ),
        (
            "[psp.settings.server]\nbind = \"127.0.0.1:1\"",
            "psp.settings.server.bind",
        ),
        (
            "[esp.settings.psp]\nurl = \"http://x\"",
            "esp.settings.psp.url",
        ),
        (
            "[esp.settings.server]\nnetwork = \"main\"",
            "esp.settings.server.network",
        ),
    ] {
        let spi = load(&scratch("conflict"), Some(file)).unwrap();
        let err = [Which::Psp, Which::Esp]
            .into_iter()
            .filter_map(|w| generate::render(&spi, w).err())
            .next()
            .unwrap_or_default();
        assert!(err.contains(needle), "{file}: {err}");
    }
}

#[test]
fn the_env_a_mint_is_started_with_names_its_folder_config_and_network() {
    let dir = scratch("env-of");
    let spi = load(&dir, None).unwrap();
    let env = generate::env(&spi, Which::Esp);
    let get = |k: &str| env.iter().find(|(n, _)| n == k).map(|(_, v)| v.clone());
    assert_eq!(get("ESP_NETWORK").as_deref(), Some("regtest"));
    assert!(get("ESP_DATA_DIR").unwrap().ends_with("esp-mint"));
    assert!(
        get("ESP_CONFIG")
            .unwrap()
            .ends_with("generated/esp-mint.toml")
    );
}
