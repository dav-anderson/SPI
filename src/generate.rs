//! The config files of psp-mint and esp-mint, written from `spi.toml`.
//!
//! Each file starts with a header that says it is generated. The values spi
//! names (network, the bitcoind connection, the addresses, the PSP URL the
//! ESP mint burns at) are set from the spi config; every other key under
//! `[psp.settings]` or `[esp.settings]` is copied as it is, so a mint setting
//! never has to be learnt by spi. A key that spi names cannot also be set under
//! `settings`: that would be two places for one value, and is refused.

use toml::{Table, Value};

use crate::config::{Spi, Which};

pub const HEADER: &str = "\
# Generated by spi. Don't edit: change spi.toml and run `spi install`, which
# writes this file again. Any edit here is lost.
";

/// The keys spi sets itself, as paths into the mint's file.
fn named(which: Which) -> &'static [&'static [&'static str]] {
    match which {
        Which::Psp => &[
            &["bitcoin", "network"],
            &["bitcoin", "rpc_url"],
            &["bitcoin", "wallet"],
            &["bitcoin", "cookie"],
            &["server", "bind"],
        ],
        Which::Esp => &[
            &["server", "bind"],
            &["server", "admin_bind"],
            &["server", "network"],
            &["psp", "url"],
        ],
    }
}

fn has_path(t: &Table, path: &[&str]) -> bool {
    match path {
        [] => true,
        [first, rest @ ..] => match t.get(*first) {
            Some(Value::Table(sub)) => has_path(sub, rest),
            Some(_) => rest.is_empty(),
            None => false,
        },
    }
}

fn put(t: &mut Table, path: &[&str], value: Value) {
    match path {
        [] => {}
        [last] => {
            t.insert((*last).to_string(), value);
        }
        [first, rest @ ..] => {
            let entry = t
                .entry((*first).to_string())
                .or_insert_with(|| Value::Table(Table::new()));
            if !matches!(entry, Value::Table(_)) {
                *entry = Value::Table(Table::new());
            }
            if let Value::Table(sub) = entry {
                put(sub, rest, value);
            }
        }
    }
}

/// The content of one mint's config file, as a table.
pub fn table(spi: &Spi, which: Which) -> Result<Table, String> {
    let m = spi.mint(which);
    let mut t = m.settings.clone();
    for path in named(which) {
        if has_path(&t, path) {
            return Err(format!(
                "{}.settings.{} is set by spi from spi.toml: remove it there and set it where spi names it ({})",
                which.env_prefix().to_lowercase(),
                path.join("."),
                match which {
                    Which::Psp => "network, [bitcoind] and [psp] bind",
                    Which::Esp =>
                        "network, [esp] bind and admin_bind; the PSP URL follows [psp] bind",
                }
            ));
        }
    }
    let s = |v: &str| Value::String(v.to_string());
    match which {
        Which::Psp => {
            put(&mut t, &["bitcoin", "network"], s(spi.network.name()));
            put(&mut t, &["bitcoin", "rpc_url"], s(&spi.rpc_url));
            put(&mut t, &["bitcoin", "wallet"], s(&spi.wallet));
            put(
                &mut t,
                &["bitcoin", "cookie"],
                s(&spi.cookie.display().to_string()),
            );
            put(&mut t, &["server", "bind"], s(&m.bind));
        }
        Which::Esp => {
            put(&mut t, &["server", "bind"], s(&m.bind));
            if let Some(a) = &m.admin_bind {
                put(&mut t, &["server", "admin_bind"], s(a));
            }
            put(&mut t, &["server", "network"], s(spi.network.name()));
            put(&mut t, &["psp", "url"], s(&spi.url(Which::Psp)));
        }
    }
    Ok(t)
}

/// The file text: the header, then the settings.
pub fn render(spi: &Spi, which: Which) -> Result<String, String> {
    let t = table(spi, which)?;
    let body = toml::to_string(&t).map_err(|e| format!("cannot write {}: {e}", which.name()))?;
    Ok(format!("{HEADER}\n{body}"))
}

/// The environment a mint is started with: where its data and its generated
/// config are, and the network. Everything else it reads from its file.
pub fn env(spi: &Spi, which: Which) -> Vec<(String, String)> {
    let p = which.env_prefix();
    vec![
        (
            format!("{p}_DATA_DIR"),
            spi.data_dir(which).display().to_string(),
        ),
        (
            format!("{p}_CONFIG"),
            spi.generated_config(which).display().to_string(),
        ),
        (format!("{p}_NETWORK"), spi.network.name().to_string()),
    ]
}
